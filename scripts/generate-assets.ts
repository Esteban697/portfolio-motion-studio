import {existsSync, mkdirSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join, relative, resolve} from 'node:path';
import {formatIssues, projectManifestSchema} from '../src/schemas/project-schema';
import {readJsonFile} from '../src/utils/read-json';

/**
 * Generates `src/generated/project-assets.ts`.
 *
 * Remotion resolves assets through the bundler, which needs static imports —
 * a manifest path is only a string at runtime. This script scans every
 * project manifest, verifies each referenced voiceover exists, and emits a
 * map of project-relative path → resolved asset URL.
 *
 * Run automatically before dev, typecheck, tests and renders (`npm run
 * assets`), and commit the output so the repo works after a fresh clone.
 */

const ROOT = process.cwd();
const PROJECTS_DIR = resolve(ROOT, 'projects');
const GENERATED_DIR = resolve(ROOT, 'src/generated');
const OUTPUT_FILE = join(GENERATED_DIR, 'project-assets.ts');

type AssetEntry = {
  projectId: string;
  /** Path as written in the manifest, relative to the project directory. */
  src: string;
  /** Import specifier from src/generated/ to the asset on disk. */
  importPath: string;
};

function fail(message: string): never {
  console.error(`\n✗ ${message}\n`);
  process.exit(1);
}

const toImportPath = (absolutePath: string): string =>
  relative(GENERATED_DIR, absolutePath).split('\\').join('/');

const projectIds = readdirSync(PROJECTS_DIR, {withFileTypes: true})
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();

const entries: AssetEntry[] = [];

for (const projectId of projectIds) {
  const manifestPath = join(PROJECTS_DIR, projectId, 'manifest.json');
  if (!existsSync(manifestPath)) {
    continue;
  }

  let raw: unknown;
  try {
    raw = readJsonFile(manifestPath);
  } catch (error) {
    fail(`Could not read JSON from ${manifestPath}\n${(error as Error).message}`);
  }

  const result = projectManifestSchema.safeParse(raw);
  if (!result.success) {
    fail(`Invalid manifest: ${relative(ROOT, manifestPath)}\n${formatIssues(result.error)}`);
  }

  const project = result.data;
  if (project.projectId !== projectId) {
    fail(
      `projectId "${project.projectId}" does not match folder name "${projectId}" (${manifestPath}).`,
    );
  }

  for (const scene of project.scenes) {
    if (!scene.voiceover) {
      continue;
    }

    const absolutePath = resolve(join(PROJECTS_DIR, projectId), scene.voiceover.src);
    if (!existsSync(absolutePath)) {
      fail(
        `Scene "${scene.id}" in ${projectId}: voiceover not found at ${scene.voiceover.src}\n` +
          `Expected: ${absolutePath}`,
      );
    }

    entries.push({
      projectId,
      src: scene.voiceover.src,
      importPath: toImportPath(absolutePath),
    });
  }
}

const imports = entries
  .map((entry, index) => `import asset${index} from '${entry.importPath}';`)
  .join('\n');

const byProject = new Map<string, AssetEntry[]>();
for (const entry of entries) {
  const list = byProject.get(entry.projectId) ?? [];
  list.push(entry);
  byProject.set(entry.projectId, list);
}

const projectBlocks = [...byProject.entries()]
  .map(([projectId, projectEntries]) => {
    const rows = projectEntries
      .map((entry) => `    '${entry.src}': asset${entries.indexOf(entry)},`)
      .join('\n');
    return `  '${projectId}': {\n${rows}\n  },`;
  })
  .join('\n');

const output = `// AUTO-GENERATED by scripts/generate-assets.ts (npm run assets). Do not edit.
// Regenerate after changing a manifest's voiceover paths or adding audio.

${imports}

export const projectAssets: Record<string, Record<string, string>> = {
${projectBlocks}
};
`;

mkdirSync(dirname(OUTPUT_FILE), {recursive: true});
writeFileSync(OUTPUT_FILE, output, 'utf8');

console.log(
  `✓ Registered ${entries.length} asset(s) across ${byProject.size} project(s) → ${relative(ROOT, OUTPUT_FILE)}`,
);
